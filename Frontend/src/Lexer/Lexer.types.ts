export type Modifier = "static" | "virtual" | "override" | "abstract" | "final" | "async" | "unsafe" | "readonly";
export type AccessModifier = "public" | "private" | "protected";
export type generalModifier = "export" | "declare";
export type TokenType = (typeof TokenTypeArray)[number];
export class Token {
	type: TokenType;
	value: string;
	rawVal: unknown;
	constructor(type: TokenType, value: string, rawVal: unknown) {
		this.type = type;
		this.value = value;
		this.rawVal = rawVal;
	}
}
